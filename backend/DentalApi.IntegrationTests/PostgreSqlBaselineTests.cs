using DentalApi.Data;
using DentalApi.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Xunit;

namespace DentalApi.IntegrationTests;

public sealed class PostgreSqlBaselineTests
{
    [Fact]
    public void Baseline_is_isolated_complete_and_generates_PostgreSql_without_a_connection()
    {
        using var pg = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        using var sqlite = new AppDbContextDesignTimeFactory().CreateDbContext([]);
        var assembly = pg.GetService<IMigrationsAssembly>();
        var entry = Assert.Single(assembly.Migrations);
        Assert.EndsWith("_PostgreSqlBaseline", entry.Key);
        Assert.DoesNotContain(entry.Key, sqlite.Database.GetMigrations());
        Assert.All(sqlite.Database.GetMigrations(), id => Assert.DoesNotContain("PostgreSql", id));
        Assert.False(pg.Database.HasPendingModelChanges());
        Assert.False(sqlite.Database.HasPendingModelChanges());

        var migration = assembly.CreateMigration(entry.Value, pg.Database.ProviderName!);
        var tables = migration.UpOperations.OfType<CreateTableOperation>().ToArray();
        Assert.Equal(pg.Model.GetEntityTypes().Select(e => e.GetTableName()).Order(),
            tables.Select(t => t.Name).Order());
        Assert.DoesNotContain(migration.UpOperations, o => o is DropTableOperation or DropColumnOperation or SqlOperation);
        var sql = pg.GetService<IMigrator>().GenerateScript(options: MigrationsSqlGenerationOptions.Idempotent);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.Contains("CREATE COLLATION", sql);
        Assert.Contains("platform_email_nocase", sql);
        Assert.Contains("timestamp without time zone", sql);
        Assert.Contains("timestamp with time zone", sql);
        Assert.Contains("CK_PatientAvailabilities_Interval", sql);
        Assert.DoesNotContain("AUTOINCREMENT", sql);
        Assert.DoesNotContain("NOCASE", sql);
        Assert.DoesNotContain("Sqlite:", sql);
        Assert.Equal(System.Data.ConnectionState.Closed, pg.Database.GetDbConnection().State);
    }

    [Fact]
    public void Provider_mappings_preserve_ticks_calendar_dates_and_concurrency()
    {
        using var db = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        var availability = db.Model.FindEntityType(typeof(PatientAvailability))!;
        Assert.Equal(typeof(long), availability.FindProperty(nameof(PatientAvailability.StartUtc))!.GetValueConverter()!.ProviderClrType);
        Assert.Equal("timestamp without time zone", db.Model.FindEntityType(typeof(Patient))!.FindProperty(nameof(Patient.DateOfBirth))!.GetColumnType());
        var birthDate = db.Model.FindEntityType(typeof(Patient))!.FindProperty(nameof(Patient.DateOfBirth))!;
        var utcBirthDate = new DateTime(2000, 1, 2, 0, 0, 0, DateTimeKind.Utc);
        var storedBirthDate = (DateTime)birthDate.GetValueConverter()!.ConvertToProvider(utcBirthDate)!;
        Assert.Equal(DateTimeKind.Unspecified, storedBirthDate.Kind);
        Assert.Equal(utcBirthDate.Ticks, storedBirthDate.Ticks);
        Assert.True(db.Model.FindEntityType(typeof(Clinic))!.FindProperty(nameof(Clinic.Version))!.IsConcurrencyToken);
        Assert.True(db.Model.FindEntityType(typeof(DoctorProfile))!.FindProperty(nameof(DoctorProfile.Version))!.IsConcurrencyToken);
    }
}

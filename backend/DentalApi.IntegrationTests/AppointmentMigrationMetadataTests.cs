    [Fact]
    public void PostgreSql_appointment_upgrade_is_additive_tenant_safe_and_generates_native_SQL_offline()
    {
        using var db = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        var assembly = db.GetService<IMigrationsAssembly>();
        var entry = Assert.Single(assembly.Migrations, m => m.Key.EndsWith("_AddPostgreSqlAppointmentFoundation"));
        var migration = assembly.CreateMigration(entry.Value, db.Database.ProviderName!);
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        Assert.Equal("Appointments", table.Name);
        Assert.All(migration.UpOperations, operation => Assert.True(operation is CreateTableOperation { Name: "Appointments" } or CreateIndexOperation { Table: "Appointments" }));
        Assert.Equal("Appointments", Assert.IsType<DropTableOperation>(Assert.Single(migration.DownOperations)).Name);
        Assert.Equal(4, table.ForeignKeys.Count);
        foreach (var fk in table.ForeignKeys)
        {
            Assert.Equal(ReferentialAction.Restrict, fk.OnDelete);
            Assert.Equal("ClinicId", fk.Columns[0]);
            Assert.Equal(fk.PrincipalTable == "Clinics" ? new[] { "Id" } : new[] { "ClinicId", "Id" }, fk.PrincipalColumns);
        }
        var timeNames = new[] { "StartUtc", "EndUtc", "OccupiedStartUtc", "OccupiedEndUtc", "CreatedAtUtc" };
        foreach (var name in timeNames)
        {
            var column = Assert.Single(table.Columns, c => c.Name == name);
            Assert.Equal("timestamp with time zone", column.ColumnType);
            Assert.False(column.IsNullable);
            var property = db.Model.FindEntityType(typeof(Appointment))!.FindProperty(name)!;
            var input = new DateTimeOffset(2026, 11, 2, 9, 0, 0, TimeSpan.FromHours(8));
            var stored = Assert.IsType<DateTimeOffset>(property.GetValueConverter()!.ConvertToProvider(input));
            Assert.Equal(TimeSpan.Zero, stored.Offset);
            Assert.Equal(input.UtcTicks, stored.UtcTicks);
        }
        Assert.Equal("uuid", Assert.Single(table.Columns, c => c.Name == "RequestId").ColumnType);
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_SnapshotIntervals" && c.Sql.Contains("INTERVAL '1 minute'"));
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_UtcRange" && c.Sql.Contains("isfinite"));
        Assert.Contains(migration.UpOperations.OfType<CreateIndexOperation>(), i => i.IsUnique && i.Columns.SequenceEqual(new[] { "ClinicId", "PatientId", "RequestId" }));
        var sql = db.GetService<IMigrator>().GenerateScript("20261027132306_PostgreSqlBaseline", entry.Key, MigrationsSqlGenerationOptions.Idempotent);
        Assert.Contains("CREATE TABLE \"Appointments\"", sql);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.DoesNotContain("CREATE COLLATION", sql);
        Assert.DoesNotContain("DROP TABLE", sql);
        Assert.DoesNotContain("ef_temp_", sql);
        Assert.DoesNotContain("AUTOINCREMENT", sql);
        Assert.DoesNotContain("600000000", sql);
        Assert.False(db.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, db.Database.GetDbConnection().State);
    }

    [Fact]
    public void SQLite_and_PostgreSql_keep_separate_migrations_and_current_snapshots()
    {
        using var sqlite = new AppDbContextDesignTimeFactory().CreateDbContext([]);
        using var pg = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        Assert.Empty(sqlite.Database.GetMigrations().Intersect(pg.Database.GetMigrations()));
        var assembly = sqlite.GetService<IMigrationsAssembly>();
        var entry = Assert.Single(assembly.Migrations, m => m.Key.EndsWith("_AddAppointmentFoundation"));
        var migration = assembly.CreateMigration(entry.Value, sqlite.Database.ProviderName!);
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        Assert.Equal("Appointments", table.Name);
        Assert.All(migration.UpOperations, operation => Assert.True(operation is CreateTableOperation { Name: "Appointments" } or CreateIndexOperation { Table: "Appointments" }));
        Assert.Equal("INTEGER", Assert.Single(table.Columns, c => c.Name == "StartUtc").ColumnType);
        Assert.Equal(typeof(long), Assert.Single(table.Columns, c => c.Name == "StartUtc").ClrType);
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_SnapshotIntervals" && c.Sql.Contains("600000000"));
        Assert.False(sqlite.Database.HasPendingModelChanges());
        Assert.False(pg.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, sqlite.Database.GetDbConnection().State);
        Assert.Equal(ConnectionState.Closed, pg.Database.GetDbConnection().State);
    }

    [Fact]
    public void Appointment_integrity_migrations_add_the_scoped_assignment_FK_and_provider_overlap_guards()
    {
        using var sqlite = new AppDbContextDesignTimeFactory().CreateDbContext([]);
        using var pg = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        var sqliteAssembly = sqlite.GetService<IMigrationsAssembly>();
        var pgAssembly = pg.GetService<IMigrationsAssembly>();
        var sqliteEntry = Assert.Single(sqliteAssembly.Migrations, m => m.Key.EndsWith("_EnforceAppointmentIntegrity"));
        var pgEntry = Assert.Single(pgAssembly.Migrations, m => m.Key.EndsWith("_EnforceAppointmentIntegrity"));
        var sqliteMigration = sqliteAssembly.CreateMigration(sqliteEntry.Value, sqlite.Database.ProviderName!);
        var pgMigration = pgAssembly.CreateMigration(pgEntry.Value, pg.Database.ProviderName!);
        var sqliteForeignKey = Assert.Single(sqliteMigration.UpOperations.OfType<AddForeignKeyOperation>(),
            operation => operation.PrincipalTable == "DoctorServices");
        var pgForeignKey = Assert.Single(pgMigration.UpOperations.OfType<AddForeignKeyOperation>(),
            operation => operation.PrincipalTable == "DoctorServices");
        Assert.Equal(new[] { "ClinicId", "DoctorProfileId", "ServiceId" }, sqliteForeignKey.Columns);
        Assert.Equal(sqliteForeignKey.Columns, sqliteForeignKey.PrincipalColumns);
        Assert.Equal(ReferentialAction.Restrict, sqliteForeignKey.OnDelete);
        Assert.Equal(new[] { "ClinicId", "DoctorProfileId", "ServiceId" }, pgForeignKey.Columns);
        Assert.Equal(pgForeignKey.Columns, pgForeignKey.PrincipalColumns);
        Assert.Equal(ReferentialAction.Restrict, pgForeignKey.OnDelete);

        var sqliteSql = string.Join("\n", sqliteMigration.UpOperations.OfType<SqlOperation>().Select(operation => operation.Sql));
        Assert.Contains("Existing appointments violate doctor-service or overlap integrity", sqliteSql);
        Assert.DoesNotContain("CREATE TRIGGER", sqliteSql);

        var sqliteOverlapEntry = Assert.Single(sqliteAssembly.Migrations, m => m.Key.EndsWith("_ProtectAppointmentOverlap"));
        var sqliteOverlapMigration = sqliteAssembly.CreateMigration(sqliteOverlapEntry.Value, sqlite.Database.ProviderName!);
        var sqliteOverlapSql = string.Join("\n", sqliteOverlapMigration.UpOperations.OfType<SqlOperation>().Select(operation => operation.Sql));
        Assert.Contains("TR_Appointments_NoDoctorOccupiedOverlap_Insert", sqliteOverlapSql);
        Assert.Contains("TR_Appointments_NoPatientTreatmentOverlap_Update", sqliteOverlapSql);
        Assert.Contains("NEW.\"OccupiedStartUtc\" < existing.\"OccupiedEndUtc\"", sqliteOverlapSql);
        Assert.Contains("NEW.\"StartUtc\" < existing.\"EndUtc\"", sqliteOverlapSql);

        var pgSql = string.Join("\n", pgMigration.UpOperations.OfType<SqlOperation>().Select(operation => operation.Sql));
        Assert.Contains("Existing appointments reference no matching doctor-service association", pgSql);
        Assert.Contains("EXCLUDE USING gist", pgSql);
        Assert.Contains("tstzrange", pgSql);
        Assert.Contains("'[)'", pgSql);
        Assert.Contains("WHERE (\"Status\" = 'Confirmed')", pgSql);
        Assert.Contains(pgMigration.UpOperations.OfType<AlterDatabaseOperation>(),
            operation => operation.GetAnnotations().Any(annotation => annotation.Name == "Npgsql:PostgresExtension:btree_gist"));
        Assert.False(sqlite.Database.HasPendingModelChanges());
        Assert.False(pg.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, sqlite.Database.GetDbConnection().State);
        Assert.Equal(ConnectionState.Closed, pg.Database.GetDbConnection().State);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Reschedule_ledger_migration_is_additive_and_preserves_appointment_overlap_guards(bool useSqlite)
    {
        using AppDbContext db = useSqlite ? new AppDbContextDesignTimeFactory().CreateDbContext([])
            : new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        var assembly = db.GetService<IMigrationsAssembly>();
        var entries = assembly.Migrations.ToArray();
        var last = entries[^1];
        Assert.EndsWith("AppointmentReschedules", last.Key);
        var migration = assembly.CreateMigration(last.Value, db.Database.ProviderName!);
        var table = Assert.IsType<CreateTableOperation>(migration.UpOperations[0]);
        Assert.Equal("AppointmentReschedules", table.Name);
        Assert.Equal(new[] { "ClinicId", "SourceId" }, table.PrimaryKey!.Columns);
        Assert.Equal(2, table.ForeignKeys.Count);
        Assert.All(table.ForeignKeys, fk =>
        {
            Assert.Equal("Appointments", fk.PrincipalTable);
            Assert.Equal(new[] { "ClinicId", "Id" }, fk.PrincipalColumns);
            Assert.Equal("ClinicId", fk.Columns[0]);
            Assert.Equal(ReferentialAction.Restrict, fk.OnDelete);
        });
        Assert.Equal(new[] { "ReplacementId", "SourceId" }, table.ForeignKeys.Select(fk => fk.Columns[1]).Order());
        var index = Assert.IsType<CreateIndexOperation>(migration.UpOperations[1]);
        Assert.Equal(2, migration.UpOperations.Count);
        Assert.True(index.IsUnique);
        Assert.Equal("AppointmentReschedules", index.Table);
        Assert.Equal(new[] { "ClinicId", "ReplacementId" }, index.Columns);
        Assert.Equal("AppointmentReschedules", Assert.IsType<DropTableOperation>(Assert.Single(migration.DownOperations)).Name);
        var sql = db.GetService<IMigrator>().GenerateScript(entries[^2].Key, last.Key);
        Assert.Contains("CREATE TABLE \"AppointmentReschedules\"", sql);
        Assert.DoesNotContain("ALTER TABLE \"Appointments\"", sql);
        Assert.DoesNotContain("DROP ", sql);
        Assert.False(db.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, db.Database.GetDbConnection().State);
    }

}

using System.Data;
using DentalApi.Data;
using DentalApi.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Xunit;

namespace DentalApi.IntegrationTests;

public sealed class AppointmentMigrationMetadataTests
{
    [Fact]
    public void PostgreSql_appointment_upgrade_is_additive_tenant_safe_and_generates_native_SQL_offline()
    {
        using var db = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        var assembly = db.GetService<IMigrationsAssembly>();
        var entry = Assert.Single(assembly.Migrations, m => m.Key.EndsWith("_AddPostgreSqlAppointmentFoundation"));
        var migration = assembly.CreateMigration(entry.Value, db.Database.ProviderName!);
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        Assert.Equal("Appointments", table.Name);
        Assert.All(migration.UpOperations, operation => Assert.True(operation is CreateTableOperation { Name: "Appointments" } or CreateIndexOperation { Table: "Appointments" }));
        Assert.Equal("Appointments", Assert.IsType<DropTableOperation>(Assert.Single(migration.DownOperations)).Name);
        Assert.Equal(4, table.ForeignKeys.Count);
        foreach (var fk in table.ForeignKeys)
        {
            Assert.Equal(ReferentialAction.Restrict, fk.OnDelete);
            Assert.Equal("ClinicId", fk.Columns[0]);
            Assert.Equal(fk.PrincipalTable == "Clinics" ? new[] { "Id" } : new[] { "ClinicId", "Id" }, fk.PrincipalColumns);
        }
        var timeNames = new[] { "StartUtc", "EndUtc", "OccupiedStartUtc", "OccupiedEndUtc", "CreatedAtUtc" };
        foreach (var name in timeNames)
        {
            var column = Assert.Single(table.Columns, c => c.Name == name);
            Assert.Equal("timestamp with time zone", column.ColumnType);
            Assert.False(column.IsNullable);
            var property = db.Model.FindEntityType(typeof(Appointment))!.FindProperty(name)!;
            var input = new DateTimeOffset(2026, 11, 2, 9, 0, 0, TimeSpan.FromHours(8));
            var stored = Assert.IsType<DateTimeOffset>(property.GetValueConverter()!.ConvertToProvider(input));
            Assert.Equal(TimeSpan.Zero, stored.Offset);
            Assert.Equal(input.UtcTicks, stored.UtcTicks);
        }
        Assert.Equal("uuid", Assert.Single(table.Columns, c => c.Name == "RequestId").ColumnType);
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_SnapshotIntervals" && c.Sql.Contains("INTERVAL '1 minute'"));
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_UtcRange" && c.Sql.Contains("isfinite"));
        Assert.Contains(migration.UpOperations.OfType<CreateIndexOperation>(), i => i.IsUnique && i.Columns.SequenceEqual(new[] { "ClinicId", "PatientId", "RequestId" }));
        var sql = db.GetService<IMigrator>().GenerateScript("20261027132306_PostgreSqlBaseline", entry.Key, MigrationsSqlGenerationOptions.Idempotent);
        Assert.Contains("CREATE TABLE \"Appointments\"", sql);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.DoesNotContain("CREATE COLLATION", sql);
        Assert.DoesNotContain("DROP TABLE", sql);
        Assert.DoesNotContain("ef_temp_", sql);
        Assert.DoesNotContain("AUTOINCREMENT", sql);
        Assert.DoesNotContain("600000000", sql);
        Assert.False(db.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, db.Database.GetDbConnection().State);
    }

    [Fact]
    public void SQLite_and_PostgreSql_keep_separate_migrations_and_current_snapshots()
    {
        using var sqlite = new AppDbContextDesignTimeFactory().CreateDbContext([]);
        using var pg = new PostgreSqlAppDbContextDesignTimeFactory().CreateDbContext([]);
        Assert.Empty(sqlite.Database.GetMigrations().Intersect(pg.Database.GetMigrations()));
        var assembly = sqlite.GetService<IMigrationsAssembly>();
        var entry = Assert.Single(assembly.Migrations, m => m.Key.EndsWith("_AddAppointmentFoundation"));
        var migration = assembly.CreateMigration(entry.Value, sqlite.Database.ProviderName!);
        var table = Assert.Single(migration.UpOperations.OfType<CreateTableOperation>());
        Assert.Equal("Appointments", table.Name);
        Assert.All(migration.UpOperations, operation => Assert.True(operation is CreateTableOperation { Name: "Appointments" } or CreateIndexOperation { Table: "Appointments" }));
        Assert.Equal("INTEGER", Assert.Single(table.Columns, c => c.Name == "StartUtc").ColumnType);
        Assert.Equal(typeof(long), Assert.Single(table.Columns, c => c.Name == "StartUtc").ClrType);
        Assert.Contains(table.CheckConstraints, c => c.Name == "CK_Appointments_SnapshotIntervals" && c.Sql.Contains("600000000"));
        Assert.False(sqlite.Database.HasPendingModelChanges());
        Assert.False(pg.Database.HasPendingModelChanges());
        Assert.Equal(ConnectionState.Closed, sqlite.Database.GetDbConnection().State);
        Assert.Equal(ConnectionState.Closed, pg.Database.GetDbConnection().State);
    }
}
